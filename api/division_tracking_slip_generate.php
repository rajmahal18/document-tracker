  if ($defaultReceivedBy === '') {
    $creatorAssistant = division_slip_assistant_name_for_principal($conn, $createdByUserId);
    if ($creatorAssistant !== '') {
      $defaultReceivedBy = $creatorAssistant;
    }
  }

  if ($defaultReceivedBy === '') {
    $defaultReceivedBy = $createdByName !== '' ? $createdByName : $actualFullName;
  }

  if ($defaultReceivedAtRaw === '') {
    $defaultReceivedAtRaw = (new DateTimeImmutable('now', new DateTimeZone('Asia/Manila')))->format('Y-m-d H:i:s');
  }

  return [
    'received_by' => $defaultReceivedBy,
    'received_at_raw' => $defaultReceivedAtRaw,
    'received_at_display' => division_slip_format_received_datetime_input($defaultReceivedAtRaw),
  ];
}

