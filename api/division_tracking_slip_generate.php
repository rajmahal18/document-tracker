  $defaultReceivedBy = trim((string)($latestDivisionReceipt['received_by'] ?? ''));
  $defaultReceivedAtRaw = trim((string)($latestDivisionReceipt['received_at'] ?? ''));

  if ($assistantMode && $actualFullName !== '') {
    $defaultReceivedBy = $actualFullName;
